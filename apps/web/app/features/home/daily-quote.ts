const epochDay = (day: string) =>
  Math.floor(Date.UTC(Number(day.slice(0, 4)), Number(day.slice(5, 7)) - 1, Number(day.slice(8, 10))) / 86_400_000);

/** The day's line: consecutive Beijing days differ, and one day keeps one line everywhere it is read. */
export function dailyQuote(day: string): DailyQuote {
  const length = DAILY_QUOTES.length;
  return DAILY_QUOTES[((epochDay(day) % length) + length) % length];
}
